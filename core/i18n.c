void i18n_set_lang(Lang l) { cur = (l >= 0 && l < LANG_COUNT) ? l : LANG_EN; }
Lang i18n_lang(void) { return cur; }

const char *tr(StrId id)
{
    if ((int)id < 0 || id >= S_COUNT) return "";
    const char *s = cur == LANG_VI ? VI[id] : EN[id];
    if (!s) s = EN[id];
    return s ? s : "";
}
